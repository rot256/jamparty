import { copyFile, readFile, readdir, writeFile } from "node:fs/promises";
import { build } from "esbuild";

function replaceOnce(source, before, after) {
  if (!source.includes(before) || source.indexOf(before) !== source.lastIndexOf(before)) {
    throw new Error("PDF.js source changed. Review the local integration patches.");
  }
  return source.replace(before, after);
}

const pdfjs = {
  name: "pdfjs-local",
  setup(builder) {
    builder.onLoad({ filter: /pdfjs-dist\/legacy\/build\/pdf(?:\.worker)?\.mjs$/ }, async ({ path }) => {
      let contents = await readFile(path, "utf8");
      if (path.endsWith("/pdf.worker.mjs")) {
        // Only the built-in decoders can run, with the same CSP as the worker.
        contents = replaceOnce(contents, [
          "await import(",
          "    /*webpackIgnore: true*/",
          "    /*@vite-ignore*/",
          '    `${WasmImage.#wasmUrl}${this._noWasmFilename}`)',
        ].join("\n"), `await ({
          "jbig2_nowasm_fallback.js": () => import("pdfjs-dist/wasm/jbig2_nowasm_fallback.js"),
          "openjpeg_nowasm_fallback.js": () => import("pdfjs-dist/wasm/openjpeg_nowasm_fallback.js"),
        })[this._noWasmFilename]()`);

        // The public view is clipped to the CropBox. Send the MediaBox
        // origin separately so cropping doesn't shift SyncTeX coordinates.
        contents = replaceOnce(contents, "userUnit,\n        view\n",
          "userUnit,\n        view,\n        mediaBox: page.mediaBox\n");
      } else {
        contents = replaceOnce(contents, "  get view() {\n    return this._pageInfo.view;",
          "  get mediaBox() { return this._pageInfo.mediaBox; }\n  get view() {\n    return this._pageInfo.view;");
      }
      return { contents, resolveDir: import.meta.dirname };
    });
  },
};

const decoderLicenses = await Promise.all([
  "LICENSE_JBIG2", "LICENSE_PDFJS_JBIG2", "LICENSE_OPENJPEG", "LICENSE_PDFJS_OPENJPEG",
].map((name) => readFile(new URL(`../../node_modules/pdfjs-dist/wasm/${name}`, import.meta.url), "utf8")));
const workerFooter = decoderLicenses.join("\n").split("\n").map((line) => line.trimEnd() ? `// ${line.trimEnd()}` : "//").join("\n");

for (const [entry, outfile] of [
  ["client/src/pdf-index.ts", "assets/pdf.js"],
  ["node_modules/pdfjs-dist/legacy/build/pdf.worker.mjs", "assets/pdf-worker.js"],
]) {
  await build({
    entryPoints: [entry], outfile, bundle: true, minify: true,
    format: "esm", target: "es2022", legalComments: "eof", plugins: [pdfjs],
    footer: entry.endsWith("/pdf.worker.mjs") ? { js: workerFooter } : undefined,
  });
}

// Keep PDF.js's packed bytes so builds reproduce across Node versions.
// The index lets the joiner serve each map on demand.
const cmaps = new URL("../../node_modules/pdfjs-dist/cmaps/", import.meta.url);
const names = (await readdir(cmaps)).filter((name) => name.endsWith(".bcmap")).sort();
const maps = await Promise.all(names.map((name) => readFile(new URL(name, cmaps))));
let offset = 0;
const ranges = names.map((name, index) => {
  const start = offset;
  offset += maps[index].length;
  return `    ${JSON.stringify(name)} => Some(${start}..${offset}),`;
});
await Promise.all([
  writeFile("assets/pdf-cmaps.bin", Buffer.concat(maps)),
  writeFile("assets/pdf-cmaps.rs", `// Generated by npm run build.
|name: &str| match name {
${ranges.join("\n")}
    _ => None,
}
`),
  copyFile(new URL("LICENSE", cmaps), "assets/pdf-cmaps-LICENSE"),
]);
